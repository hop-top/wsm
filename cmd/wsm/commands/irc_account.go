// newIRCAccountCmd builds the `wsm irc account` group.
func newIRCAccountCmd(opts *globalOptions) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "account",
		Short: "Manage member accounts on a workspace's IRC server",
		Long: `Create, rotate and suspend the server accounts wsm provisions.

Managed mode owns every account on its server, so all three operations
work. External mode depends on what the provider supports: a backend
without account creation reports the operation as unsupported rather
than pretending to have done it.

Accounts are never deleted, only suspended. Event attribution is keyed by
account name, so removing one would orphan every message that member
ever sent.`,
		RunE: groupOnlyRunE,
	}
	// Depth-3 leaves (wsm irc account create) require kit/hierarchical on
	// every intermediate ancestor; without it kit's shape validator
	// refuses the whole tree at startup.
	cli.SetHierarchical(cmd)
	cmd.AddCommand(
		newIRCAccountCreateCmd(opts),
		newIRCAccountRotateCmd(opts),
		newIRCAccountSuspendCmd(opts),
	)
	return cmd
}

// ircAccountOp names the three account operations, so the shared runner
// can report which one a provider could not perform.
type ircAccountOp string

const (
	opCreate  ircAccountOp = "create"
	opRotate  ircAccountOp = "rotate"
	opSuspend ircAccountOp = "suspend"
)

// capFor reports the provider capability this operation requires.
func (op ircAccountOp) capFor() provider.Caps {
	switch op {
	case opCreate:
		return provider.CapCreateAccount
	case opRotate:
		return provider.CapSetPassword
	default:
		return provider.CapSuspendAccount
	}
}

// newIRCAccountCreateCmd builds `wsm irc account create`.
func newIRCAccountCreateCmd(opts *globalOptions) *cobra.Command {
	var raw string

	cmd := &cobra.Command{
		Use:   "create <workspace> [member]",
		Short: "Create a member's account on the IRC server",
		Long: `Provision one account on the workspace's IRC server.

The passphrase is generated by wsm, recorded in the workspace's secrets
file and applied to the server in the same run, so the credential wsm
hands out through 'wsm irc creds' is always the one the server accepts.

--raw <name> provisions an arbitrary account instead of a member's. That
is how a host operator gives a cross-machine guest access to a server
the guest's own wsm cannot reach: the password is printed once and is
NOT stored, because the account belongs to the guest rather than to this
workspace, and keeping a copy would make this workspace's secrets file
the weakest link in someone else's credential.`,
		Args: cobra.RangeArgs(1, 2),
		RunE: func(cmd *cobra.Command, args []string) error {
			return withApp(opts, func(ctx context.Context, app *appContext) error {
				return runIRCAccount(ctx, cmd, app, opts, opCreate, args, raw)
			})
		},
	}
	cmd.Flags().StringVar(&raw, "raw", "", "Provision this account name instead of a member's")

	cli.SetSideEffect(cmd, cli.SideEffectWriteShared)
	cli.SetIdempotency(cmd, cli.IdempotencyConditional)
	return cmd
}

