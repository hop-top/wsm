// ircAccountDoc is the `wsm irc account ... --json` document.
type ircAccountDoc struct {
	Workspace string       `json:"workspace"`
	ID        string       `json:"id"`
	Operation ircAccountOp `json:"operation"`
	Account   string       `json:"account"`
	Server    string       `json:"server"`

	// Password is present only when this run produced a credential the
	// caller must capture: a --raw provisioning, which wsm does not
	// store. A member account's passphrase goes to the secrets file and
	// is read back with `wsm irc creds`, so it is not echoed here.
	Password string `json:"password,omitempty"`
	// Stored reports whether wsm recorded the passphrase.
	Stored bool `json:"stored"`
	// Existed reports an account the server already had, which create
	// treats as success.
	Existed bool `json:"existed,omitempty"`
	// Sensitive marks a document carrying a credential.
	Sensitive bool `json:"sensitive,omitempty"`
}

// runIRCAccount performs one account operation.
//
// The three verbs share a runner because they share everything that is
// hard: resolving the account, opening a session against the right
// server, deciding whether the provider can do the job at all, and
// keeping the secrets file consistent with what the server accepted.
// Only the provider call and the secret handling differ.
func runIRCAccount(
	ctx context.Context,
	cmd *cobra.Command,
	app *appContext,
	opts *globalOptions,
	op ircAccountOp,
	args []string,
	rawAccount string,
) error {
	ref := args[0]
	member := ""
	if len(args) > 1 {
		member = args[1]
	}

	if err := validateAccountTarget(member, rawAccount); err != nil {
		return err
	}

	rt, err := resolveIRCRuntime(ctx, app, ref)
	if err != nil {
		return err
	}
	// Provisioning accounts on a server is the same authority as
	// enabling IRC for the workspace: both decide who exists on it.
	if err := requireCapability(app, workspace.CapIRCEnable); err != nil {
		return err
	}
	profile, err := rt.loadEnabledProfile()
	if err != nil {
		return err
	}

	account := strings.TrimSpace(rawAccount)
	isRaw := account != ""
	if !isRaw {
		if account, err = resolveMemberAccount(ctx, rt, profile, member); err != nil {
			return err
		}
	}

	doc := ircAccountDoc{
		Workspace: rt.ws.Name,
		ID:        rt.ws.ID,
		Operation: op,
		Account:   account,
		Server:    serverIDOf(rt, profile),
	}

	if done, derr := previewDryRun(cmd,
		map[string]any{
			"workspace": rt.ws.Name,
			"account":   account,
			"operation": string(op),
			"raw":       isRaw,
		},
		cli.Effect{
			Kind:       "update",
			Target:     "irc-account:" + account,
			Reversible: op != opRotate,
			Detail: fmt.Sprintf("%s account %q on %s",
				op, account, serverIDOf(rt, profile)),
		},
	); done {
		return derr
	}

	session, err := openIRCSession(ctx, rt, profile)
	if err != nil {
		return err
	}
	defer session.Close()

	accounts := session.providers.Accounts
	if !accounts.Caps().Has(op.capFor()) {
		return unsupportedByProvider(profile, op, account)
	}

	secrets, err := irc.LoadSecrets(rt.paths.Secrets)
	if err != nil {
		return workspace.NewErrorBackend("load irc secrets", err)
	}

	switch op {
	case opCreate, opRotate:
		passphrase, gerr := irc.GeneratePassphrase()
		if gerr != nil {
			return workspace.NewErrorBackend("generate passphrase", gerr)
		}

		if op == opCreate {
			cerr := accounts.CreateAccount(ctx, account, passphrase)
			switch {
			case errors.Is(cerr, provider.ErrExists):
				// An existing account keeps its credential: overwriting
				// it here would invalidate whatever the member is
				// already using, which a create must never do.
				doc.Existed = true
				passphrase = ""
			case cerr != nil:
				return accountOperationError(profile, op, account, cerr)
			}
		} else {
			if serr := accounts.SetPassword(ctx, account, passphrase); serr != nil {
				return accountOperationError(profile, op, account, serr)
			}
		}

		if passphrase != "" {
			if isRaw {
				// A guest's credential is theirs, not this workspace's:
				// printed once, never written to our secrets file.
				doc.Password = passphrase
				doc.Sensitive = true
			} else {
				// Recorded only after the server accepted it, so wsm
				// never holds a passphrase the server does not have.
				secrets.Set(account, passphrase)
				if serr := secrets.Save(rt.paths.Secrets); serr != nil {
					return workspace.NewErrorBackend("save irc secrets", serr)
				}
				doc.Stored = true
			}
		}

	case opSuspend:
		if serr := accounts.Suspend(ctx, account); serr != nil {
			return accountOperationError(profile, op, account, serr)
		}
	}

	if opts.Quiet {
		return nil
	}
	if isMachineFormat(opts) {
		return output.Render(os.Stdout, machineFormat(opts), doc)
	}
	return renderIRCAccountResult(doc)
}

// validateAccountTarget refuses an invocation that names neither a
// member nor a raw account, or both.
func validateAccountTarget(member, raw string) error {
	member = strings.TrimSpace(member)
	raw = strings.TrimSpace(raw)

	switch {
	case member == "" && raw == "":
		return &output.Error{
			Code:         output.CodeUsage,
			Message:      "name a member, or pass --raw <account>",
			SuggestedFix: "wsm irc account create <workspace> <member>",
			ExitCode:     2,
		}
	case member != "" && raw != "":
		return &output.Error{
			Code:         output.CodeUsage,
			Message:      "--raw and a member argument are mutually exclusive",
			SuggestedFix: "pass one or the other, not both",
			ExitCode:     2,
		}
	}
	return nil
}

// unsupportedByProvider is the exit-7 refusal for a capability the
// backend does not advertise.
//
// Exit 7 rather than 2: the invocation is well-formed and the fix is an
// environment change (configure the ergo HTTP API, give the bot oper,
// switch providers), which is exactly what the prerequisite class is
// for. The message names both the provider and the operation, because
// "unsupported" alone leaves the operator guessing which half to fix.
func unsupportedByProvider(profile irc.Profile, op ircAccountOp, account string) error {
	return workspace.NewErrorPrerequisitePermanent(fmt.Sprintf(
		"provider %q does not support %s account (%s): "+
			"configure the provider's account backend, or provision %q on the server directly",
		profile.Provider, op, capabilityHint(op), account,
	))
}

// capabilityHint names what a provider would need for this operation,
// so the message points at a setting rather than at a concept.
func capabilityHint(op ircAccountOp) string {
	switch op {
	case opCreate, opRotate:
		return "needs the ergo HTTP API: set irc.server.ergo_api"
	default:
		return "needs the bot to hold oper"
	}
}

// accountOperationError maps a provider failure onto the exit-code
// contract.
//
// ErrUnsupported reaching this point means the provider advertised the
// capability and then declined anyway, which is still an environment
// problem rather than a runtime fault. Everything else is exit 1: the
// server rejected a well-formed request.
func accountOperationError(profile irc.Profile, op ircAccountOp, account string, err error) error {
	if errors.Is(err, provider.ErrUnsupported) {
		return unsupportedByProvider(profile, op, account)
	}
	return &output.Error{
		Code:     output.CodeGeneric,
		Message:  fmt.Sprintf("%s account %q: %v", op, account, err),
		ExitCode: 1,
	}
}

// ircAccountRow is the table projection.
type ircAccountRow struct {
	Field string `table:"FIELD,priority=9" json:"field"`
	Value string `table:"VALUE,priority=9" json:"value"`
}

// renderIRCAccountResult renders the human-readable outcome.
func renderIRCAccountResult(doc ircAccountDoc) error {
	rows := []ircAccountRow{
		{Field: "ACCOUNT", Value: doc.Account},
		{Field: "OPERATION", Value: string(doc.Operation)},
		{Field: "SERVER", Value: doc.Server},
	}
	if doc.Existed {
		rows = append(rows, ircAccountRow{Field: "EXISTED", Value: "true"})
	}
	if doc.Password != "" {
		rows = append(rows, ircAccountRow{Field: "PASSWORD", Value: doc.Password})
	}
	if err := output.Render(os.Stdout, output.Table, rows); err != nil {
		return err
	}

	// §6.3: guidance is non-data → stderr.
	if doc.Password != "" {
		fmt.Fprintln(os.Stderr,
			"This passphrase is shown once and is not stored by wsm. Record it now.")
	}
	if doc.Existed {
		fmt.Fprintf(os.Stderr,
			"Account %q already existed; its credential was left unchanged.\n", doc.Account)
	}
	return nil
}

// ircSession is a short-lived bot session and the provider trio built
// over it.
//
// The daemon holds one of these for its whole life; these commands need
// one for a single operation. It deliberately does NOT take the
// workspace lock: the lock means "I am the daemon for this workspace",
// and an account operation is legitimate while the daemon runs. What it
// must not do is capture, record or move cursors, and it does none of
// those — it opens a session, issues one command and leaves.
type ircSession struct {
	transport *bot.Transport
	providers provider.Providers
}

// Close tears the session down.
func (s *ircSession) Close() {
	if s.transport != nil {
		s.transport.Close()
	}
}

// openIRCSession dials the workspace's server and builds its providers.
//
// This mirrors the daemon's own connect path (pkg/irc/daemon: transport
// options, then the provider trio built with the bot's account so
// MyRole and CS TRANSFER work). It is reproduced rather than shared
// because the daemon's copy is method-bound to a running Daemon; the
// shapes are pinned by a unit test so the two cannot drift silently.
func openIRCSession(ctx context.Context, rt *ircRuntime, profile irc.Profile) (*ircSession, error) {
	opts, err := ircTransportOptions(rt, profile)
	if err != nil {
		return nil, err
	}

	transport := bot.New(opts)
	if cerr := transport.Connect(ctx); cerr != nil {
		return nil, workspace.NewErrorPrerequisiteTransient(fmt.Sprintf(
			"connect to %s: %v", opts.Addr, cerr))
	}

	deps := provider.Deps{
		Transport: transport,
		API:       ircAPIConfig(rt, profile),
	}

	var providers provider.Providers
	account := botAccountOf(rt, profile)
	if profile.Provider == irc.ProviderErgo {
		providers, err = ergo.NewWithAccount(deps, account)
	} else {
		providers, err = provider.Open(string(profile.Provider), deps)
		if err == nil {
			if setter, ok := providers.Roles.(interface{ SetNick(string) }); ok {
				setter.SetNick(account)
			}
		}
	}
	if err != nil {
		transport.Close()
		// Unclassified: opening a provider fails on a stale API token
		// (permanent) as readily as on an API that is briefly down
		// (transient), and the provider returns both the same way.
		return nil, workspace.NewErrorPrerequisite(fmt.Sprintf(
			"open provider %q: %v", profile.Provider, err))
	}

	return &ircSession{transport: transport, providers: providers}, nil
}

// ircTransportOptions builds the session options for a workspace's mode.
//
// Managed connects to its own loopback plaintext listener and opers up,
// exactly as the daemon does: the listener never leaves 127.0.0.1, so
// plaintext there is not a downgrade, and the rendered oper block is
// keyed by the bot's account. External connects to the configured
// server, with TLS unless the operator turned it off.
func ircTransportOptions(rt *ircRuntime, profile irc.Profile) (bot.Options, error) {
	secrets, err := irc.LoadSecrets(rt.paths.Secrets)
	if err != nil {
		return bot.Options{}, workspace.NewErrorBackend("load irc secrets", err)
	}
	password, err := irc.ReadBotPassword(rt.cfg, secrets)
	if err != nil {
		if errors.Is(err, irc.ErrNoBotSecret) {
			return bot.Options{}, workspace.NewErrorNotConfigured(fmt.Sprintf(
				"no password for bot account %q: re-enable the workspace with "+
					"--bot-password-stdin, or set irc.bot.secret_ref",
				rt.cfg.Bot.Account))
		}
		// Unclassified: as in provisionExternal, an unresolvable
		// secret_ref may be a missing entry or an unavailable store.
		return bot.Options{}, workspace.NewErrorPrerequisite(err.Error())
	}

	account := botAccountOf(rt, profile)
	opts := bot.Options{
		Account:  account,
		Password: password,
		Nick:     account,
		Backoff:  irc.NewBackoff(),
	}

	if profile.Mode == irc.ModeManaged {
		if !profile.Ports.Valid() {
			return bot.Options{}, workspace.NewErrorNotConfigured(
				"this managed workspace has no port triple recorded: re-enable it")
		}
		opts.Addr = net.JoinHostPort(irc.DefaultBind, strconv.Itoa(profile.Ports.Plain))
		opts.OperName = account
		opts.OperPass = password
		return opts, nil
	}

	if strings.TrimSpace(rt.cfg.Server.Host) == "" {
		return bot.Options{}, workspace.NewErrorNotConfigured(
			"irc.server.host is empty: set the server this workspace connects to")
	}
	opts.Addr = net.JoinHostPort(rt.cfg.Server.Host, strconv.Itoa(rt.cfg.Server.Port))
	if rt.cfg.Server.TLSEnabled() {
		opts.TLS = &tls.Config{
			ServerName:         rt.cfg.Server.Host,
			InsecureSkipVerify: rt.cfg.Server.InsecureSkipVerify, //nolint:gosec // operator-configured, surfaced as a status warning
			MinVersion:         tls.VersionTLS12,
		}
	}
	return opts, nil
}
